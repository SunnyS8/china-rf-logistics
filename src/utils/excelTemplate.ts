import * as XLSX from 'xlsx';

/**
 * Пустой шаблон для ручного ввода ставок.
 * Важно: парсер читает свободные тексты в столбце A — каждая строка должна
 * содержать полный маршрут со всеми статьями затрат (фрахт, ЖД, авто,
 * экспедирование, терминал, срок).
 */
export function downloadExcelTemplate(): void {
  const rows = [
    ['Маршрут Шанхай → Владивосток → Москва (Ворсино) → Серпухов, 40HC 26тн, Морской фрахт 2100 USD, ЖД 210000 руб, Автовывоз 28000 руб, Экспедирование 15000 руб, Терминальные 25000 руб, срок 25-32 дн, перевес 2000 руб/т, НДС 20%'],
    ['Маршрут прямое ЖД Шанхай → Забайкальск → Краснодар-Сорт. → Ставрополь, 40HC 26тн, Фрахт прямое ЖД 5680 USD, Автовывоз 48000 руб, Экспедирование 20000 руб, Терминальные 15000 руб, срок 20-26 дн, перевес 1500 руб/т, НДС 20%'],
    ['Маршрут Шанхай → Владивосток → Ростов-Товарный → Ставрополь, 20GP 18тн, Морской фрахт 1450 USD, ЖД 150000 руб, Автовывоз 38000 руб, Экспедирование 12000 руб, Терминальные 18000 руб, срок 28-35 дн, НДС 20%'],
  ];

  const instructions = [
    ['Шаблон ручного ввода ставок перевозчиков'],
    [''],
    ['Как заполнять:'],
    ['1. Назовите файл именем перевозчика, например «ТрансЛогистика.xlsx».'],
    ['2. Каждая строка столбца A — один маршрут со всеми затратами.'],
    ['3. Поддерживаемые статьи:'],
    ['   - Морской фрахт / Фрахт ... USD (или CNY, EUR, руб)'],
    ['   - ЖД ... руб (железнодорожная ставка)'],
    ['   - Автовывоз ... руб (доставка до склада)'],
    ['   - Экспедирование ... руб (вознаграждение экспедитора)'],
    ['   - Терминальные ... руб (терминал / растаможка)'],
    ['   - срок 25-32 дн — срок доставки'],
    ['   - перевес 2000 руб/т — доплата за каждую лишнюю тонну'],
    ['   - 40HC или 20GP — тип контейнера, 26тн — вес груза'],
    ['   - НДС 20% / НДС 5% / без НДС — ставка НДС на росс. услуги'],
    ['4. Укажите в тексте строки город назначения: «Серпухов» или «Ставрополь».'],
    [''],
    ['Строку-пример можно удалить или заменить своими данными.'],
  ];

  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.aoa_to_sheet(rows);
  ws['!cols'] = [{ wch: 180 }];
  XLSX.utils.book_append_sheet(wb, ws, 'Тарифы');

  const ws2 = XLSX.utils.aoa_to_sheet(instructions);
  ws2['!cols'] = [{ wch: 90 }];
  XLSX.utils.book_append_sheet(wb, ws2, 'Инструкция');

  XLSX.writeFile(wb, 'Шаблон_ставок.xlsx');
}